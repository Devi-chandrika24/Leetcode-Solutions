import urllib.request
import json
import os
import datetime

USERNAME = 'Devi_chandrika24'
LEETCODE_API_ENDPOINT = 'https://leetcode.com/graphql'

def fetch_leetcode_data(username):
    query = """
    query getUserProfile($username: String!) {
      matchedUser(username: $username) {
        username
        submitStats: submitStatsGlobal {
          acSubmissionNum {
            difficulty
            count
            submissions
          }
        }
        profile {
          realName
          userAvatar
          ranking
          reputation
        }
        userCalendar {
          streak
          totalActiveDays
        }
      }
      recentAcSubmissionList(username: $username, limit: 20) {
        id
        title
        titleSlug
        timestamp
      }
      userProfileUserQuestionProgressV2(userSlug: $username) {
        userSessionBeatsPercentage {
          difficulty
          percentage
        }
      }
    }
    """
    
    headers = {
        'Content-Type': 'application/json',
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
        'Referer': f'https://leetcode.com/u/{username}/'
    }
    
    data = json.dumps({'query': query, 'variables': {'username': username}}).encode('utf-8')
    req = urllib.request.Request(LEETCODE_API_ENDPOINT, data=data, headers=headers)
    
    try:
        with urllib.request.urlopen(req) as resp:
            return json.loads(resp.read().decode('utf-8'))
    except Exception as e:
        print(f"Error fetching data: {e}")
        return None

def generate_readme(data):
    if not data or 'data' not in data or not data['data']['matchedUser']:
        return "Failed to fetch data."

    user_data = data['data']['matchedUser']
    stats = {item['difficulty']: item['count'] for item in user_data['submitStats']['acSubmissionNum']}
    
    beats = {item['difficulty']: item['percentage'] for item in data['data']['userProfileUserQuestionProgressV2']['userSessionBeatsPercentage']}
    
    recent_submissions = data['data']['recentAcSubmissionList']
    
    readme_content = f"""# 🚀 LeetCode Solutions & Profile 🚀

![Banner](https://assets.leetcode.com/users/YsFBYGpdFz/avatar_1755576095.png)

Welcome to my **LeetCode Solutions** repository! This repository contains my personal solutions to various LeetCode problems and auto-updates my latest activity and statistics directly from my [LeetCode Profile](https://leetcode.com/u/{USERNAME}/).

---

## 📊 Profile Stats

* **Name**: {user_data['profile']['realName']}
* **Global Ranking**: {user_data['profile']['ranking']}
* **Current Streak**: 🔥 {user_data['userCalendar']['streak']} days
* **Total Active Days**: {user_data['userCalendar']['totalActiveDays']} days

### 💡 Problem Solving Progress
- **Total Solved**: {stats.get('All', 0)}
- 🟢 **Easy**: {stats.get('Easy', 0)} (Beats {beats.get('EASY', 0)}%)
- 🟡 **Medium**: {stats.get('Medium', 0)} (Beats {beats.get('MEDIUM', 0)}%)
- 🔴 **Hard**: {stats.get('Hard', 0)} (Beats {beats.get('HARD', 0)}%)

<br>
<div align="center">
  <img src="https://leetcard.jacoblin.cool/{USERNAME}?theme=dark&font=Inter&ext=activity" alt="LeetCode Stat Card" />
</div>
<br>

---

## 🕒 Recent Accepted Submissions

Here are some of my most recently solved problems:

| Problem | Time Solved |
| :--- | :--- |
"""

    for sub in recent_submissions:
        dt = datetime.datetime.fromtimestamp(int(sub['timestamp'])).strftime('%Y-%m-%d %H:%M:%S')
        readme_content += f"| [{sub['title']}](https://leetcode.com/problems/{sub['titleSlug']}/) | {dt} |\n"

    readme_content += """
---

## 📁 Repository Structure

Solutions are organized by difficulty (if applicable) or conceptually. The repository structure is updated automatically. 

* *This README is auto-generated by a GitHub Action running a Python script.*
"""
    return readme_content

def update_readme_file(content):
    with open('README.md', 'w', encoding='utf-8') as f:
        f.write(content)
    print("README.md updated successfully!")

def create_problem_folders(recent_submissions):
    # Just creating placeholder folders for recent ones to demonstrate structure
    for sub in recent_submissions:
        title_slug = sub['titleSlug']
        folder_name = title_slug
        if not os.path.exists(folder_name):
            os.makedirs(folder_name)
            
            # Create a placeholder solution file if it doesn't exist
            readme_path = os.path.join(folder_name, 'README.md')
            if not os.path.exists(readme_path):
                with open(readme_path, 'w', encoding='utf-8') as f:
                    f.write(f"# {sub['title']}\n\n[LeetCode Link](https://leetcode.com/problems/{title_slug}/)\n\n## Solution\n\nSolution code will go here.\n")

if __name__ == "__main__":
    print(f"Fetching data for {USERNAME}...")
    data = fetch_leetcode_data(USERNAME)
    if data:
        print("Data fetched. Generating README...")
        readme_content = generate_readme(data)
        update_readme_file(readme_content)
        
        print("Ensuring solution folders exist...")
        create_problem_folders(data['data']['recentAcSubmissionList'])
        print("Done!")
    else:
        print("Failed to sync.")
